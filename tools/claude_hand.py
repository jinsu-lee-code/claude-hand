"""claude-hand: one Claude Code subagent per open Unity project (MCP for Unity / CoplayDev).

  list    Show the Unity editors MCP for Unity can see right now.
  sync    Write a subagent definition (unity-<project>.md) for each of them, plus the
          supervisor skill, into your Claude Code folders.
  guard   PreToolUse hook used by those subagents: blocks any Unity call that would reach
          a project other than the subagent's own. Not meant to be run by hand.

Run with uv (already installed for MCP for Unity) or any Python 3.10+:
  uv run tools/claude_hand.py list
  uv run tools/claude_hand.py sync
"""

from __future__ import annotations

import argparse
import json
import os
import re
import socket
import sys
import urllib.error
import urllib.request
from dataclasses import dataclass, field
from pathlib import Path

TOOL_PATH = Path(__file__).resolve()
REPO_ROOT = TOOL_PATH.parent.parent
SKILL_SOURCE = REPO_ROOT / "skills" / "unity-orchestrator" / "SKILL.md"
GENERATED_MARKER = "<!-- generated by claude-hand sync; edits are overwritten on the next sync -->"
DEFAULT_STDIO_ARGS = ["--from", "mcpforunityserver", "mcp-for-unity", "--transport", "stdio"]
UNITY_PACKAGE_HINTS = ("mcp-for-unity", "mcpforunityserver", "unity-mcp")


# --------------------------------------------------------------------------- data


@dataclass
class Instance:
    """One running Unity editor as MCP for Unity identifies it: Name@hash."""

    name: str
    hash: str
    path: str = ""
    port: int | None = None
    unity_version: str = ""
    alive: bool = True
    source: str = ""

    @property
    def id(self) -> str:
        return f"{self.name}@{self.hash}"


@dataclass
class ServerConfig:
    """How the user's existing Unity MCP entry starts the server; copied into each subagent."""

    transport: str  # "stdio" | "http"
    command: str = "uvx"
    args: list[str] = field(default_factory=lambda: list(DEFAULT_STDIO_ARGS))
    env: dict[str, str] = field(default_factory=dict)
    url: str = ""
    key: str = "unityMCP"
    origin: str = "default"


# --------------------------------------------------------------------------- discovery


def status_dir() -> Path:
    env = os.environ.get("UNITY_MCP_STATUS_DIR")
    return Path(env) if env else Path.home() / ".unity-mcp"


def project_name_from_assets_path(project_path: str) -> str:
    """Same rule as MCP for Unity: '.../MyGame/Assets' -> 'MyGame'."""
    path = project_path.rstrip("/\\")
    if path.endswith("Assets"):
        path = path[: -len("Assets")].rstrip("/\\")
    name = re.split(r"[/\\]", path)[-1] if path else ""
    return name or "Unknown"


def probe_port(port: int, timeout: float = 0.4) -> bool:
    """MCP for Unity's listener greets every connection with a handshake containing FRAMING=1."""
    try:
        with socket.create_connection(("127.0.0.1", port), timeout) as s:
            s.settimeout(timeout)
            return b"FRAMING=1" in s.recv(512)
    except OSError:
        return False


def discover_stdio(directory: Path | None = None, probe=probe_port) -> list[Instance]:
    """Read ~/.unity-mcp/unity-mcp-status-<hash>.json files written by the Unity side (stdio bridge)."""
    directory = directory or status_dir()
    by_port: dict[object, tuple[Instance, float]] = {}
    for file in sorted(directory.glob("unity-mcp-status-*.json")):
        try:
            data = json.loads(file.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        project_path = data.get("project_path") or ""
        port = data.get("unity_port")
        inst = Instance(
            name=project_name_from_assets_path(project_path),
            hash=file.stem.replace("unity-mcp-status-", ""),
            path=project_path[: -len("/Assets")] if project_path.endswith(("/Assets", "\\Assets")) else project_path,
            port=port if isinstance(port, int) else None,
            unity_version=data.get("unity_version") or "",
            alive=bool(isinstance(port, int) and probe(port)) or bool(data.get("reloading")),
            source=str(file),
        )
        mtime = file.stat().st_mtime
        key = inst.port if inst.port is not None else inst.hash
        if key not in by_port or by_port[key][1] < mtime:
            by_port[key] = (inst, mtime)
    return [entry[0] for entry in sorted(by_port.values(), key=lambda e: e[0].name.lower())]


def http_base(url: str) -> str:
    """'http://localhost:8080/mcp' -> 'http://localhost:8080'."""
    match = re.match(r"^(https?://[^/]+)", url.strip())
    return match.group(1) if match else url.rstrip("/")


def discover_http(url: str, fetch=None) -> list[Instance]:
    """Ask a running MCP for Unity HTTP server which editors are connected (GET /api/instances)."""
    fetch = fetch or _fetch_json
    try:
        payload = fetch(http_base(url) + "/api/instances")
    except (OSError, ValueError, urllib.error.URLError):
        return []
    instances = []
    for item in payload.get("instances", []) if isinstance(payload, dict) else []:
        project, hash_ = item.get("project"), item.get("hash")
        if project and hash_:
            instances.append(Instance(name=project, hash=hash_, unity_version=item.get("unity_version") or "", source="http"))
    return sorted(instances, key=lambda i: i.name.lower())


def _fetch_json(url: str):
    with urllib.request.urlopen(url, timeout=3) as response:  # noqa: S310 - localhost only
        return json.loads(response.read().decode("utf-8"))


# --------------------------------------------------------------------------- config detection


def candidate_config_files(cwd: Path | None = None) -> list[Path]:
    cwd = cwd or Path.cwd()
    home = Path.home()
    files = [cwd / ".mcp.json", home / ".claude.json"]
    appdata = os.environ.get("APPDATA")
    if appdata:
        files.append(Path(appdata) / "Claude" / "claude_desktop_config.json")
    files.append(home / "Library" / "Application Support" / "Claude" / "claude_desktop_config.json")
    files.append(home / ".config" / "Claude" / "claude_desktop_config.json")
    return files


def _server_maps(data: dict) -> list[dict]:
    maps = []
    if isinstance(data.get("mcpServers"), dict):
        maps.append(data["mcpServers"])
    for project in (data.get("projects") or {}).values():  # ~/.claude.json keeps per-project servers here
        if isinstance(project, dict) and isinstance(project.get("mcpServers"), dict):
            maps.append(project["mcpServers"])
    return maps


def looks_like_unity_server(key: str, entry: dict) -> bool:
    if not isinstance(entry, dict):
        return False
    blob = " ".join([key, str(entry.get("command", "")), " ".join(map(str, entry.get("args", []) or [])), str(entry.get("url", ""))]).lower()
    return "unity" in key.lower() or any(h in blob for h in UNITY_PACKAGE_HINTS)


def detect_server_config(files: list[Path] | None = None) -> ServerConfig:
    """Find the user's Unity MCP entry so every subagent starts the server the same way."""
    for file in files if files is not None else candidate_config_files():
        try:
            data = json.loads(file.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        for servers in _server_maps(data):
            # Prefer the canonical key, then anything that looks like MCP for Unity.
            for key in sorted(servers, key=lambda k: (k != "unityMCP", k)):
                entry = servers[key]
                if not looks_like_unity_server(key, entry):
                    continue
                if entry.get("url") or entry.get("type") == "http":
                    return ServerConfig(transport="http", url=entry.get("url", "http://localhost:8080/mcp"), key=key, origin=str(file))
                if entry.get("command"):
                    return ServerConfig(
                        transport="stdio",
                        command=entry["command"],
                        args=[str(a) for a in entry.get("args", [])],
                        env={str(k): str(v) for k, v in (entry.get("env") or {}).items()},
                        key=key,
                        origin=str(file),
                    )
    return ServerConfig(transport="stdio")


# --------------------------------------------------------------------------- generation


def slug(name: str) -> str:
    s = re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")
    return (s or "project")[:40].rstrip("-")


def agent_names(instances: list[Instance]) -> dict[str, str]:
    """instance id -> subagent name; projects that share a folder name get a hash suffix."""
    counts: dict[str, int] = {}
    for inst in instances:
        counts[slug(inst.name)] = counts.get(slug(inst.name), 0) + 1
    return {
        inst.id: f"unity-{slug(inst.name)}" + (f"-{inst.hash[:4]}" if counts[slug(inst.name)] > 1 else "")
        for inst in instances
    }


def server_key(agent_name: str) -> str:
    """MCP server key inside the subagent; tools then appear as mcp__<key>__<tool>."""
    return agent_name.replace("-", "_")


def pinned_args(args: list[str], pin: str) -> list[str]:
    out, skip = [], False
    for a in args:
        if skip:
            skip = False
            continue
        if a == "--default-instance":
            skip = True
            continue
        if a.startswith("--default-instance="):
            continue
        out.append(a)
    return out + ["--default-instance", pin]


def q(value: str) -> str:
    """A JSON string is a valid YAML double-quoted scalar."""
    return json.dumps(value, ensure_ascii=False)


def hook_command(runner: str, pin: str, key: str, transport: str) -> str:
    """Works in Git Bash (Claude Code's default hook shell on Windows) and in PowerShell."""
    script = TOOL_PATH.as_posix()
    return f'{runner} "{script}" guard --pin "{pin}" --server {key} --transport {transport}'


def render_agent(inst: Instance, name: str, server: ServerConfig, runner: str, allowlist: bool, focus_nudge: bool) -> str:
    key = server_key(name)
    lines = [
        "---",
        f"name: {name}",
        "description: " + q(
            f"Unity 프로젝트 {inst.name} 전담 작업자 ({inst.id}). 이 프로젝트의 씬·오브젝트·에셋을 보거나 고칠 때, "
            f"또는 다른 Unity 프로젝트와 오브젝트를 주고받을 때 맡긴다. 이 프로젝트 말고는 건드리지 못한다."
        ),
    ]
    if allowlist:
        lines.append("tools: " + q(f"mcp__{key}__*, Read, Glob, Grep"))
    else:
        lines.append("disallowedTools: " + q(f"mcp__{server.key}__*"))
    lines += ["mcpServers:", f"  - {key}:"]
    if server.transport == "http":
        lines += ["      type: http", f"      url: {q(server.url)}"]
    else:
        env = dict(server.env)
        if not focus_nudge:
            env.setdefault("UNITY_MCP_DISABLE_FOCUS_NUDGE", "1")
        lines += [
            "      type: stdio",
            f"      command: {q(server.command)}",
            "      args: " + json.dumps(pinned_args(server.args, inst.id), ensure_ascii=False),
        ]
        if env:
            lines.append("      env:")
            lines += [f"        {k}: {q(v)}" for k, v in sorted(env.items())]
    lines += [
        "hooks:",
        "  PreToolUse:",
        '    - matcher: "mcp__.*"',
        "      hooks:",
        "        - type: command",
        "          command: " + q(hook_command(runner, inst.id, key, server.transport)),
        "---",
        GENERATED_MARKER,
        "",
        render_agent_prompt(inst, key, server.transport),
    ]
    return "\n".join(lines) + "\n"


def render_agent_prompt(inst: Instance, key: str, transport: str) -> str:
    first_step = (
        f'- 첫 Unity 호출 전에 `set_active_instance(instance="{inst.id}")`를 호출한다. 다른 값은 안전장치가 막는다.\n'
        if transport == "http"
        else ""
    )
    location = f" (경로: `{inst.path}`)" if inst.path else ""
    return f"""# Unity 프로젝트 전담: {inst.name}

너는 Unity 프로젝트 **{inst.name}**{location} 하나만 맡는 작업자다. 연결 대상은 `{inst.id}`로 고정돼 있다.

## 지킬 것
{first_step}- 시작하면 `ch_editor_status`로 연결된 프로젝트가 {inst.name}인지 확인한다. 다르면 아무것도 바꾸지 말고 감독에게 보고한다.
- Unity 도구는 `{key}` 서버 것만 쓴다. 호출에 `unity_instance`를 넣지 않는다.
- 다른 프로젝트 일을 받으면 하지 말고, 그 프로젝트 담당(unity-…)에게 넘겨야 한다고 감독에게 돌려준다.
- 씬 저장(`manage_scene`의 `save`)은 요청받았을 때만 한다.

## 작업 순서: 스냅샷 → ref → 행동 → 확인
1. `ch_scene_snapshot`으로 씬을 보고 대상의 ref(`@s1a2b3c4:e5` 형태)를 고른다. 씬이 크면 `depth`를 낮추고 `root=<ref>`로 파고든다.
2. `ch_*` 도구에는 ref를, MCP for Unity 기본 도구에는 노드의 `path`나 `instance_id`를 넘긴다.
3. 바꾼 뒤에는 스냅샷을 다시 찍어 결과를 확인한다. `STALE_REF`가 나오면 새 스냅샷의 ref를 쓴다.
4. 오류의 `retry`가 `safe`면 그대로 다시, `after_fix`면 인자를 고쳐서, `check_first`면 상태부터 확인하고 다시 한다.
5. `ch_*` 도구가 목록에 없으면 먼저 `manage_tools(action="sync")`로 Unity의 도구 목록을 다시 받아온다. 그래도 없으면 `execute_custom_tool(tool_name="ch_scene_snapshot", parameters={{...}})`처럼 부른다.

## 다른 프로젝트와 오브젝트 주고받기
- 보낼 때: 스냅샷으로 ref 확인 → `ch_export_objects(refs=[...], name="...")` → 결과의 `manifest_path`를 그대로 감독에게 돌려준다.
- 받을 때: `ch_import_package(manifest=..., dry_run=true)`로 먼저 확인한다. `would_overwrite`, `same_guid_elsewhere`, `missing_packages`, `warnings` 중 하나라도 있으면 멈추고 감독에게 그대로 보고한다. 문제가 없으면 `dry_run` 없이 실행하고, 결과의 `placed` ref를 보고한다.

## 보고
마지막 답에는 한 일, 바뀐 것(ref, 경로, manifest_path), 남은 문제를 짧게 적는다. 감독이 다른 세션에 그대로 넘길 값은 정확히 옮긴다.
"""


@dataclass
class SyncResult:
    written: list[Path] = field(default_factory=list)
    unchanged: list[Path] = field(default_factory=list)
    removed: list[Path] = field(default_factory=list)


def sync_agents(instances: list[Instance], agents_dir: Path, server: ServerConfig, runner: str,
                allowlist: bool = True, focus_nudge: bool = False, prune: bool = False, dry_run: bool = False) -> SyncResult:
    result = SyncResult()
    names = agent_names(instances)
    wanted = set()
    if not dry_run:
        agents_dir.mkdir(parents=True, exist_ok=True)
    for inst in instances:
        path = agents_dir / f"{names[inst.id]}.md"
        wanted.add(path.name)
        text = render_agent(inst, names[inst.id], server, runner, allowlist, focus_nudge)
        if path.exists() and path.read_text(encoding="utf-8") == text:
            result.unchanged.append(path)
            continue
        if path.exists() and GENERATED_MARKER not in path.read_text(encoding="utf-8"):
            raise SystemExit(f"{path} exists and was not written by claude-hand; rename it or remove it first.")
        if not dry_run:
            path.write_text(text, encoding="utf-8", newline="\n")
        result.written.append(path)
    if prune and agents_dir.exists():
        for path in agents_dir.glob("unity-*.md"):
            if path.name not in wanted and GENERATED_MARKER in path.read_text(encoding="utf-8"):
                if not dry_run:
                    path.unlink()
                result.removed.append(path)
    return result


def install_skill(skills_dir: Path, dry_run: bool = False) -> Path:
    target = skills_dir / "claude-hand-unity" / "SKILL.md"
    if not dry_run:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(SKILL_SOURCE.read_text(encoding="utf-8"), encoding="utf-8", newline="\n")
    return target


# --------------------------------------------------------------------------- guard (PreToolUse hook)


def instance_matches(value: str, pin: str) -> bool:
    """Accept only identifiers that MCP for Unity would resolve to the pinned editor."""
    value = str(value).strip()
    name, _, hash_ = pin.partition("@")
    if value in (pin, name, hash_):
        return True
    if "@" in value:
        v_name, _, v_hint = value.partition("@")
        return v_name == name and len(v_hint) >= 4 and hash_.startswith(v_hint)
    return len(value) >= 4 and hash_.startswith(value) and not value.isdigit()


def find_instance_values(obj) -> list[str]:
    """Every unity_instance value anywhere in the tool input (batch_execute nests commands)."""
    found = []
    if isinstance(obj, dict):
        for k, v in obj.items():
            if k == "unity_instance" and v not in (None, ""):
                found.append(str(v))
            else:
                found += find_instance_values(v)
    elif isinstance(obj, list):
        for item in obj:
            found += find_instance_values(item)
    return found


def guard_decision(event: dict, pin: str, server: str, transport: str) -> str | None:
    """Return a denial reason, or None to let the call through."""
    tool = str(event.get("tool_name", ""))
    if not tool.startswith("mcp__"):
        return None
    prefix = f"mcp__{server}__"
    if not tool.startswith(prefix):
        return f"이 하위 세션은 {pin} 전용입니다. Unity 도구는 {prefix}* 만 쓸 수 있습니다."
    short = tool[len(prefix):]
    tool_input = event.get("tool_input") or {}
    if short == "set_active_instance":
        target = str(tool_input.get("instance", ""))
        if transport == "http" and instance_matches(target, pin):
            return None
        return f"대상 프로젝트는 {pin}로 고정돼 있어 바꿀 수 없습니다."
    for value in find_instance_values(tool_input):
        if not instance_matches(value, pin):
            return f"unity_instance={value!r}는 이 하위 세션의 프로젝트({pin})가 아닙니다. unity_instance 없이 호출하세요."
    return None


def run_guard(args: argparse.Namespace, stdin=None, stdout=None) -> int:
    stdin, stdout = stdin or sys.stdin, stdout or sys.stdout
    try:
        event = json.loads(stdin.read() or "{}")
        reason = guard_decision(event, args.pin, args.server, args.transport)
    except Exception as exc:  # fail closed: a broken guard must not let calls through
        reason = f"claude-hand guard 오류로 호출을 막았습니다: {exc}"
    if reason:
        json.dump({
            "hookSpecificOutput": {
                "hookEventName": "PreToolUse",
                "permissionDecision": "deny",
                "permissionDecisionReason": reason,
            }
        }, stdout)  # ASCII-escaped: safe whatever code page the hook shell uses
    return 0


# --------------------------------------------------------------------------- CLI


def gather_instances(server: ServerConfig, extra: list[str], include_dead: bool) -> list[Instance]:
    if server.transport == "http":
        found = discover_http(server.url) or [i for i in discover_stdio() if i.alive]
    else:
        found = discover_stdio()
    if not include_dead:
        found = [i for i in found if i.alive]
    known = {i.id for i in found}
    for raw in extra:
        name, sep, hash_ = raw.partition("@")
        if not sep or not name or not hash_:
            raise SystemExit(f"--instance needs Name@hash, got {raw!r}")
        if raw not in known:
            found.append(Instance(name=name, hash=hash_, source="--instance"))
    return found


def cmd_list(args: argparse.Namespace) -> int:
    server = detect_server_config()
    instances = gather_instances(server, args.instance, include_dead=True)
    print(f"MCP 설정: {server.transport} ({server.origin})")
    if not instances:
        print("열려 있는 Unity 프로젝트를 찾지 못했습니다. Unity에서 Window > MCP for Unity 상태가 Connected인지 확인하세요.")
        return 1
    names = agent_names(instances)
    for inst in instances:
        state = "실행 중" if inst.alive else "응답 없음"
        print(f"  {names[inst.id]:<28} {inst.id:<36} {state:<6} {inst.unity_version} {inst.path}")
    return 0


def cmd_sync(args: argparse.Namespace) -> int:
    server = detect_server_config()
    instances = gather_instances(server, args.instance, include_dead=args.include_dead)
    if not instances:
        print("열려 있는 Unity 프로젝트가 없습니다. 하위 세션을 만들 프로젝트를 Unity로 먼저 여세요.")
        return 1
    agents_dir = Path(args.agents_dir).expanduser()
    result = sync_agents(instances, agents_dir, server, args.runner, allowlist=not args.no_allowlist,
                         focus_nudge=args.keep_focus_nudge, prune=args.prune, dry_run=args.dry_run)
    prefix = "(dry run) " if args.dry_run else ""
    print(f"{prefix}MCP 설정: {server.transport} ({server.origin})")
    for p in result.written:
        print(f"{prefix}작성: {p}")
    for p in result.unchanged:
        print(f"{prefix}그대로: {p}")
    for p in result.removed:
        print(f"{prefix}삭제: {p}")
    if not args.no_skill:
        print(f"{prefix}스킬: {install_skill(Path(args.skills_dir).expanduser(), args.dry_run)}")
    print("Claude Code에서 /agents 로 unity-* 하위 세션이 보이는지 확인하세요. agents 폴더를 처음 만든 경우에만 Claude Code를 다시 시작하면 됩니다.")
    return 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="claude_hand", description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)

    p_list = sub.add_parser("list", help="show Unity editors MCP for Unity can see")
    p_list.add_argument("--instance", action="append", default=[], metavar="NAME@HASH", help="add an editor by hand")
    p_list.set_defaults(func=cmd_list)

    p_sync = sub.add_parser("sync", help="write one subagent per Unity editor (+ the supervisor skill)")
    p_sync.add_argument("--agents-dir", default=str(Path.home() / ".claude" / "agents"))
    p_sync.add_argument("--skills-dir", default=str(Path.home() / ".claude" / "skills"))
    p_sync.add_argument("--instance", action="append", default=[], metavar="NAME@HASH", help="add an editor by hand")
    p_sync.add_argument("--include-dead", action="store_true", help="also write agents for editors that do not answer")
    p_sync.add_argument("--prune", action="store_true", help="delete generated unity-*.md for editors that are gone")
    p_sync.add_argument("--runner", default="uv run -q --no-project", help="how the guard hook starts Python")
    p_sync.add_argument("--no-allowlist", action="store_true", help="use disallowedTools instead of a tools allowlist")
    p_sync.add_argument("--keep-focus-nudge", action="store_true", help="let MCP for Unity pull Unity to the front during tests")
    p_sync.add_argument("--no-skill", action="store_true", help="do not install the supervisor skill")
    p_sync.add_argument("--dry-run", action="store_true")
    p_sync.set_defaults(func=cmd_sync)

    p_guard = sub.add_parser("guard", help="PreToolUse hook (used by generated subagents)")
    p_guard.add_argument("--pin", required=True)
    p_guard.add_argument("--server", required=True)
    p_guard.add_argument("--transport", choices=["stdio", "http"], default="stdio")
    p_guard.set_defaults(func=run_guard)
    return parser


def main(argv: list[str] | None = None) -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")  # Korean output in Windows consoles
    args = build_parser().parse_args(argv)
    return args.func(args)


if __name__ == "__main__":
    raise SystemExit(main())
