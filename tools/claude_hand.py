class SyncResult:
    written: list[Path] = field(default_factory=list)
    unchanged: list[Path] = field(default_factory=list)
    removed: list[Path] = field(default_factory=list)


def build_agent_files(unity: list[Instance], unity_server: ServerConfig | None,
                      blender: list[BlenderInstance], blender_server: ServerConfig | None,
                      runner: str, allowlist: bool = True, focus_nudge: bool = False) -> dict[str, str]:
    """file name -> contents for every subagent to write."""
    files: dict[str, str] = {}
    if unity:
        names = agent_names(unity)
        for inst in unity:
            files[f"{names[inst.id]}.md"] = render_agent(inst, names[inst.id], unity_server or ServerConfig(transport="stdio"),
                                                         runner, allowlist, focus_nudge)
    if blender:
        names = blender_agent_names(blender)
        server = blender_server or ServerConfig(transport="stdio", command="uvx", args=list(DEFAULT_BLENDER_ARGS), key="blender")
        for inst in blender:
            files[f"{names[inst.id]}.md"] = render_blender_agent(inst, names[inst.id], server, runner, allowlist)
    return files


def write_agent_files(files: dict[str, str], agents_dir: Path, prune: bool = False, dry_run: bool = False) -> SyncResult:
    result = SyncResult()
    for file_name in files:
        path = agents_dir / file_name
        if path.exists() and GENERATED_MARKER not in path.read_text(encoding="utf-8"):
            raise SystemExit(f"{path} exists and was not written by claude-hand; rename it or remove it first.")
    if not dry_run:
        agents_dir.mkdir(parents=True, exist_ok=True)
    for file_name, text in files.items():
        path = agents_dir / file_name
        if path.exists() and path.read_text(encoding="utf-8") == text:
            result.unchanged.append(path)
            continue
        if not dry_run:
            path.write_text(text, encoding="utf-8", newline="\n")
        result.written.append(path)
    if prune and agents_dir.exists():
        for pattern in ("unity-*.md", "blender-*.md"):
            for path in agents_dir.glob(pattern):
                if path.name not in files and GENERATED_MARKER in path.read_text(encoding="utf-8"):
                    if not dry_run:
                        path.unlink()
                    result.removed.append(path)
    return result


def sync_agents(instances: list[Instance], agents_dir: Path, server: ServerConfig, runner: str,
                allowlist: bool = True, focus_nudge: bool = False, prune: bool = False, dry_run: bool = False,
                blender: list[BlenderInstance] | None = None, blender_server: ServerConfig | None = None) -> SyncResult:
    files = build_agent_files(instances, server, blender or [], blender_server, runner, allowlist, focus_nudge)
    return write_agent_files(files, agents_dir, prune=prune, dry_run=dry_run)


