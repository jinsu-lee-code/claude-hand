def with_port(args: list[str], port: int) -> list[str]:
    out, skip = [], False
    for a in args:
        if skip:
            skip = False
            continue
        if a == "--port":
            skip = True
            continue
        if a.startswith("--port="):
            continue
        out.append(a)
    return out + ["--port", str(port)]


