def main(argv: list[str] | None = None) -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")  # Korean output in Windows consoles
    args = build_parser().parse_args(argv)
    return args.func(args)


