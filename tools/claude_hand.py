@dataclass
class SyncResult:
    written: list[Path] = field(default_factory=list)
    unchanged: list[Path] = field(default_factory=list)
    removed: list[Path] = field(default_factory=list)


def build_agent_files(unity: list[Instance], unity_server: ServerConfig | None,
                      blender: list[BlenderInstance], blender_server: ServerConfig | None,
                      runner: str, allowlist: bool = True, focus_nudge: bool = False) -> dict[str, str]:
    """file name -> contents for every subagent to write."""
    files: dict[str, str] = {}
    if unity:
        names = agent_names(unity)
        for inst in unity:
            files[f"{names[inst.id]}.md"] = render_agent(inst, names[inst.id], unity_server or ServerConfig(transport="stdio"),
                                                         runner, allowlist, focus_nudge)
    if blender:
        names = blender_agent_names(blender)
        server = blender_server or ServerConfig(transport="stdio", command="uvx", args=list(DEFAULT_BLENDER_ARGS), key="blender")
        for inst in blender:
            files[f"{names[inst.id]}.md"] = render_blender_agent(inst, names[inst.id], server, runner, allowlist)
    return files


def write_agent_files(files: dict[str, str], agents_dir: Path, prune: bool = False, dry_run: bool = False) -> SyncResult:
    result = SyncResult()
    for file_name in files:
        path = agents_dir / file_name
        if path.exists() and GENERATED_MARKER not in path.read_text(encoding="utf-8"):
            raise SystemExit(f"{path} exists and was not written by claude-hand; rename it or remove it first.")
    if not dry_run:
        agents_dir.mkdir(parents=True, exist_ok=True)
    for file_name, text in files.items():
        path = agents_dir / file_name
        if path.exists() and path.read_text(encoding="utf-8") == text:
            result.unchanged.append(path)
            continue
        if not dry_run:
            path.write_text(text, encoding="utf-8", newline="\n")
        result.written.append(path)
    if prune and agents_dir.exists():
        for pattern in ("unity-*.md", "blender-*.md"):
            for path in agents_dir.glob(pattern):
                if path.name not in files and GENERATED_MARKER in path.read_text(encoding="utf-8"):
                    if not dry_run:
                        path.unlink()
                    result.removed.append(path)
    return result


def sync_agents(instances: list[Instance], agents_dir: Path, server: ServerConfig, runner: str,
                allowlist: bool = True, focus_nudge: bool = False, prune: bool = False, dry_run: bool = False,
                blender: list[BlenderInstance] | None = None, blender_server: ServerConfig | None = None) -> SyncResult:
    files = build_agent_files(instances, server, blender or [], blender_server, runner, allowlist, focus_nudge)
    return write_agent_files(files, agents_dir, prune=prune, dry_run=dry_run)


def install_skill(skills_dir: Path, dry_run: bool = False) -> Path:
    target = skills_dir / "claude-hand" / "SKILL.md"
    if not dry_run:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(SKILL_SOURCE.read_text(encoding="utf-8"), encoding="utf-8", newline="\n")
    return target


# --------------------------------------------------------------------------- guard (PreToolUse hook)


def instance_matches(value: str, pin: str) -> bool:
    """Accept only identifiers that MCP for Unity would resolve to the pinned editor."""
    value = str(value).strip()
    name, _, hash_ = pin.partition("@")
    if value in (pin, name, hash_):
        return True
    if "@" in value:
        v_name, _, v_hint = value.partition("@")
        return v_name == name and len(v_hint) >= 4 and hash_.startswith(v_hint)
    return len(value) >= 4 and hash_.startswith(value) and not value.isdigit()


def find_instance_values(obj) -> list[str]:
    """Every unity_instance value anywhere in the tool input (batch_execute nests commands)."""
    found = []
    if isinstance(obj, dict):
        for k, v in obj.items():
            if k == "unity_instance" and v not in (None, ""):
                found.append(str(v))
            else:
                found += find_instance_values(v)
    elif isinstance(obj, list):
        for item in obj:
            found += find_instance_values(item)
    return found


def guard_decision(event: dict, pin: str, server: str, transport: str, app: str = "unity") -> str | None:
    """Return a denial reason, or None to let the call through."""
    tool = str(event.get("tool_name", ""))
    if not tool.startswith("mcp__"):
        return None
    prefix = f"mcp__{server}__"
    if not tool.startswith(prefix):
        what = "Blender" if app == "blender" else "Unity"
        return f"이 하위 세션은 {pin} 전용입니다. {what} 도구는 {prefix}* 만 쓸 수 있습니다."
    if app == "blender":
        return None  # one MCP for Blender server talks to exactly one port, so its own tools cannot reach another Blender
    short = tool[len(prefix):]
    tool_input = event.get("tool_input") or {}
    if short == "set_active_instance":
        target = str(tool_input.get("instance", ""))
        if transport == "http" and instance_matches(target, pin):
            return None
        return f"대상 프로젝트는 {pin}로 고정돼 있어 바꿀 수 없습니다."
    for value in find_instance_values(tool_input):
        if not instance_matches(value, pin):
            return f"unity_instance={value!r}는 이 하위 세션의 프로젝트({pin})가 아닙니다. unity_instance 없이 호출하세요."
    return None


def run_guard(args: argparse.Namespace, stdin=None, stdout=None) -> int:
    stdin, stdout = stdin or sys.stdin, stdout or sys.stdout
    try:
        event = json.loads(stdin.read() or "{}")
        reason = guard_decision(event, args.pin, args.server, args.transport, args.app)
    except Exception as exc:  # fail closed: a broken guard must not let calls through
        reason = f"claude-hand guard 오류로 호출을 막았습니다: {exc}"
    if reason:
        json.dump({
            "hookSpecificOutput": {
                "hookEventName": "PreToolUse",
                "permissionDecision": "deny",
                "permissionDecisionReason": reason,
            }
        }, stdout)  # ASCII-escaped: safe whatever code page the hook shell uses
    return 0


