@dataclass
class Instance:
    """One running Unity editor as MCP for Unity identifies it: Name@hash."""

    name: str
    hash: str
    path: str = ""
    port: int | None = None
    unity_version: str = ""
    alive: bool = True
    source: str = ""

    @property
    def id(self) -> str:
        return f"{self.name}@{self.hash}"


@dataclass
class BlenderInstance:
    """One Blender window running the MCP for Blender add-on, identified by its socket port."""

    port: int
    filepath: str = ""
    blender_version: str = ""
    alive: bool = True
    source: str = "probe"

    @property
    def name(self) -> str:
        stem = re.split(r"[/\\]", self.filepath)[-1] if self.filepath else ""
        stem = stem[:-6] if stem.lower().endswith(".blend") else stem
        return stem or f"untitled-{self.port}"

    @property
    def id(self) -> str:
        return f"{self.name}@{self.port}"


@dataclass
class ServerConfig:
    """How the user's existing Unity MCP entry starts the server; copied into each subagent."""

    transport: str  # "stdio" | "http"
    command: str = "uvx"
    args: list[str] = field(default_factory=lambda: list(DEFAULT_STDIO_ARGS))
    env: dict[str, str] = field(default_factory=dict)
    url: str = ""
    key: str = "unityMCP"
    origin: str = "default"
    warning: str = ""


# --------------------------------------------------------------------------- discovery


def status_dir() -> Path:
    env = os.environ.get("UNITY_MCP_STATUS_DIR")
    return Path(env) if env else Path.home() / ".unity-mcp"


def project_name_from_assets_path(project_path: str) -> str:
    """Same rule as MCP for Unity: '.../MyGame/Assets' -> 'MyGame'."""
    path = project_path.rstrip("/\\")
    if path.endswith("Assets"):
        path = path[: -len("Assets")].rstrip("/\\")
    name = re.split(r"[/\\]", path)[-1] if path else ""
    return name or "Unknown"


def probe_port(port: int, timeout: float = 0.4) -> bool:
    """MCP for Unity's listener greets every connection with a handshake containing FRAMING=1."""
    try:
        with socket.create_connection(("127.0.0.1", port), timeout) as s:
            s.settimeout(timeout)
            return b"FRAMING=1" in s.recv(512)
    except OSError:
        return False


def discover_stdio(directory: Path | None = None, probe=probe_port) -> list[Instance]:
    """Read ~/.unity-mcp/unity-mcp-status-<hash>.json files written by the Unity side (stdio bridge)."""
    directory = directory or status_dir()
    by_port: dict[object, tuple[Instance, float]] = {}
    for file in sorted(directory.glob("unity-mcp-status-*.json")):
        try:
            data = json.loads(file.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        project_path = data.get("project_path") or ""
        port = data.get("unity_port")
        inst = Instance(
            name=project_name_from_assets_path(project_path),
            hash=file.stem.replace("unity-mcp-status-", ""),
            path=project_path[: -len("/Assets")] if project_path.endswith(("/Assets", "\\Assets")) else project_path,
            port=port if isinstance(port, int) else None,
            unity_version=data.get("unity_version") or "",
            alive=bool(isinstance(port, int) and probe(port)) or bool(data.get("reloading")),
            source=str(file),
        )
        mtime = file.stat().st_mtime
        key = inst.port if inst.port is not None else inst.hash
        if key not in by_port or by_port[key][1] < mtime:
            by_port[key] = (inst, mtime)
    return [entry[0] for entry in sorted(by_port.values(), key=lambda e: e[0].name.lower())]


def http_base(url: str) -> str:
    """'http://localhost:8080/mcp' -> 'http://localhost:8080'."""
    match = re.match(r"^(https?://[^/]+)", url.strip())
    return match.group(1) if match else url.rstrip("/")


def discover_http(url: str, fetch=None) -> list[Instance]:
    """Ask a running MCP for Unity HTTP server which editors are connected (GET /api/instances)."""
    fetch = fetch or _fetch_json
    try:
        payload = fetch(http_base(url) + "/api/instances")
    except (OSError, ValueError, urllib.error.URLError):
        return []
    instances = []
    for item in payload.get("instances", []) if isinstance(payload, dict) else []:
        project, hash_ = item.get("project"), item.get("hash")
        if project and hash_:
            instances.append(Instance(name=project, hash=hash_, unity_version=item.get("unity_version") or "", source="http"))
    return sorted(instances, key=lambda i: i.name.lower())


def _fetch_json(url: str):
    with urllib.request.urlopen(url, timeout=3) as response:  # noqa: S310 - localhost only
        return json.loads(response.read().decode("utf-8"))


def parse_ports(spec: str) -> list[int]:
    """'9876-9879,9900' -> [9876, 9877, 9878, 9879, 9900]."""
    ports: list[int] = []
    for part in filter(None, (p.strip() for p in spec.split(","))):
        low, sep, high = part.partition("-")
        values = range(int(low), int(high) + 1) if sep else [int(low)]
        ports += [p for p in values if 1024 <= p <= 65535 and p not in ports]
    return ports


def blender_request(port: int, command: dict, timeout: float = 2.0):
    """MCP for Blender's add-on speaks bare JSON over TCP: one object in, one object out."""
    with socket.create_connection(("127.0.0.1", port), timeout) as s:
        s.settimeout(timeout)
        s.sendall(json.dumps(command).encode("utf-8"))
        buffer = b""
        while True:
            chunk = s.recv(65536)
            if not chunk:
                break
            buffer += chunk
            try:
                return json.loads(buffer.decode("utf-8"))
            except (UnicodeDecodeError, ValueError):
                continue  # partial message
    return None


def discover_blender(ports: list[int], request=blender_request) -> list[BlenderInstance]:
    """Ping each port; for every MCP for Blender add-on that answers, read its .blend path (read-only)."""
    found = []
    for port in ports:
        try:
            pong = request(port, {"type": "ping", "params": {}}, 2.0)
        except OSError:
            continue  # nothing listening
        if not (isinstance(pong, dict) and pong.get("status") == "success"):
            continue  # something else owns the port (e.g. the official Blender Lab add-on)
        inst = BlenderInstance(port=port)
        try:
            info = request(port, {"type": "get_addon_info", "params": {}}, 3.0)
            inst.blender_version = str((info or {}).get("result", {}).get("blender_version", ""))
        except (OSError, AttributeError):
            pass
        try:
            code = "import bpy\nprint(bpy.data.filepath)"
            res = request(port, {"type": "execute_code", "params": {"code": code}}, 5.0)
            inst.filepath = str((res or {}).get("result", {}).get("result", "")).strip()
        except (OSError, AttributeError):
            pass
        found.append(inst)
    return found


# --------------------------------------------------------------------------- config detection


def candidate_config_files(cwd: Path | None = None) -> list[Path]:
    cwd = cwd or Path.cwd()
    home = Path.home()
    files = [cwd / ".mcp.json", home / ".claude.json"]
    appdata = os.environ.get("APPDATA")
    if appdata:
        files.append(Path(appdata) / "Claude" / "claude_desktop_config.json")
    files.append(home / "Library" / "Application Support" / "Claude" / "claude_desktop_config.json")
    files.append(home / ".config" / "Claude" / "claude_desktop_config.json")
    return files


def _server_maps(data: dict) -> list[dict]:
    maps = []
    if isinstance(data.get("mcpServers"), dict):
        maps.append(data["mcpServers"])
    for project in (data.get("projects") or {}).values():  # ~/.claude.json keeps per-project servers here
        if isinstance(project, dict) and isinstance(project.get("mcpServers"), dict):
            maps.append(project["mcpServers"])
    return maps


def looks_like_unity_server(key: str, entry: dict) -> bool:
    if not isinstance(entry, dict):
        return False
    blob = " ".join([key, str(entry.get("command", "")), " ".join(map(str, entry.get("args", []) or [])), str(entry.get("url", ""))]).lower()
    return "unity" in key.lower() or any(h in blob for h in UNITY_PACKAGE_HINTS)


def detect_server_config(files: list[Path] | None = None) -> ServerConfig:
    """Find the user's Unity MCP entry so every subagent starts the server the same way."""
    for file in files if files is not None else candidate_config_files():
        try:
            data = json.loads(file.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        for servers in _server_maps(data):
            # Prefer the canonical key, then anything that looks like MCP for Unity.
            for key in sorted(servers, key=lambda k: (k != "unityMCP", k)):
                entry = servers[key]
                if not looks_like_unity_server(key, entry):
                    continue
                if entry.get("url") or entry.get("type") == "http":
                    return ServerConfig(transport="http", url=entry.get("url", "http://localhost:8080/mcp"), key=key, origin=str(file))
                if entry.get("command"):
                    return ServerConfig(
                        transport="stdio",
                        command=entry["command"],
                        args=[str(a) for a in entry.get("args", [])],
                        env={str(k): str(v) for k, v in (entry.get("env") or {}).items()},
                        key=key,
                        origin=str(file),
                    )
    return ServerConfig(transport="stdio")


def _entry_blob(key: str, entry: dict) -> str:
    return " ".join([key, str(entry.get("command", "")), " ".join(map(str, entry.get("args", []) or []))]).lower()


def looks_like_blender_server(key: str, entry: dict) -> bool:
    return isinstance(entry, dict) and ("blender" in key.lower() or any(h in _entry_blob(key, entry) for h in BLENDER_PACKAGE_HINTS))


def detect_blender_config(files: list[Path] | None = None) -> ServerConfig:
    """Find the user's MCP for Blender entry. Anything that is not the GitHub add-on's server
    (for example the official Blender Lab server) is not wired up yet, so fall back to the default."""
    for file in files if files is not None else candidate_config_files():
        try:
            data = json.loads(file.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        for servers in _server_maps(data):
            for key in sorted(servers):
                entry = servers[key]
                if not looks_like_blender_server(key, entry) or not entry.get("command"):
                    continue
                if not any(h in _entry_blob(key, entry) for h in BLENDER_PACKAGE_HINTS):
                    return ServerConfig(
                        transport="stdio", command="uvx", args=list(DEFAULT_BLENDER_ARGS), key=key, origin="default",
                        warning=f"'{key}' ({file}) is not MCP for Blender (GitHub); subagents use 'uvx mcp-for-blender' instead.",
                    )
                return ServerConfig(
                    transport="stdio",
                    command=entry["command"],
                    args=[str(a) for a in entry.get("args", [])],
                    env={str(k): str(v) for k, v in (entry.get("env") or {}).items()},
                    key=key,
                    origin=str(file),
                )
    return ServerConfig(transport="stdio", command="uvx", args=list(DEFAULT_BLENDER_ARGS), key="blender")


# --------------------------------------------------------------------------- generation


def slug(name: str) -> str:
    s = re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")
    return (s or "project")[:40].rstrip("-")


def agent_names(instances: list[Instance]) -> dict[str, str]:
    """instance id -> subagent name; projects that share a folder name get a hash suffix."""
    counts: dict[str, int] = {}
    for inst in instances:
        counts[slug(inst.name)] = counts.get(slug(inst.name), 0) + 1
    return {
        inst.id: f"unity-{slug(inst.name)}" + (f"-{inst.hash[:4]}" if counts[slug(inst.name)] > 1 else "")
        for inst in instances
    }


def server_key(agent_name: str) -> str:
    """MCP server key inside the subagent; tools then appear as mcp__<key>__<tool>."""
    return agent_name.replace("-", "_")


def pinned_args(args: list[str], pin: str) -> list[str]:
    out, skip = [], False
    for a in args:
        if skip:
            skip = False
            continue
        if a == "--default-instance":
            skip = True
            continue
        if a.startswith("--default-instance="):
            continue
        out.append(a)
    return out + ["--default-instance", pin]


def q(value: str) -> str:
    """A JSON string is a valid YAML double-quoted scalar."""
    return json.dumps(value, ensure_ascii=False)


def hook_command(runner: str, pin: str, key: str, transport: str, app: str = "unity") -> str:
    """Works in Git Bash (Claude Code's default hook shell on Windows) and in PowerShell."""
    script = TOOL_PATH.as_posix()
    return f'{runner} "{script}" guard --pin "{pin}" --server {key} --transport {transport} --app {app}'


def hook_block(command: str) -> list[str]:
    return [
        "hooks:",
        "  PreToolUse:",
        '    - matcher: "mcp__.*"',
        "      hooks:",
        "        - type: command",
        "          command: " + q(command),
    ]


def render_agent(inst: Instance, name: str, server: ServerConfig, runner: str, allowlist: bool, focus_nudge: bool) -> str:
    key = server_key(name)
    lines = [
        "---",
        f"name: {name}",
        "description: " + q(
            f"Unity 프로젝트 {inst.name} 전담 작업자 ({inst.id}). 이 프로젝트의 씬·오브젝트·에셋을 보거나 고칠 때, "
            f"또는 다른 Unity 프로젝트와 오브젝트를 주고받을 때 맡긴다. 이 프로젝트 말고는 건드리지 못한다."
        ),
    ]
    if allowlist:
        lines.append("tools: " + q(f"mcp__{key}__*, Read, Glob, Grep"))
    else:
        lines.append("disallowedTools: " + q(f"mcp__{server.key}__*"))
    lines += ["mcpServers:", f"  - {key}:"]
    if server.transport == "http":
        lines += ["      type: http", f"      url: {q(server.url)}"]
    else:
        env = dict(server.env)
        if not focus_nudge:
            env.setdefault("UNITY_MCP_DISABLE_FOCUS_NUDGE", "1")
        lines += [
            "      type: stdio",
            f"      command: {q(server.command)}",
            "      args: " + json.dumps(pinned_args(server.args, inst.id), ensure_ascii=False),
        ]
        if env:
            lines.append("      env:")
            lines += [f"        {k}: {q(v)}" for k, v in sorted(env.items())]
    lines += hook_block(hook_command(runner, inst.id, key, server.transport, "unity"))
    lines += ["---", GENERATED_MARKER, "", render_agent_prompt(inst, key, server.transport)]
    return "\n".join(lines) + "\n"


def render_agent_prompt(inst: Instance, key: str, transport: str) -> str:
    first_step = (
        f'- 첫 Unity 호출 전에 `set_active_instance(instance="{inst.id}")`를 호출한다. 다른 값은 안전장치가 막는다.\n'
        if transport == "http"
        else ""
    )
    location = f" (경로: `{inst.path}`)" if inst.path else ""
    return f"""# Unity 프로젝트 전담: {inst.name}

너는 Unity 프로젝트 **{inst.name}**{location} 하나만 맡는 작업자다. 연결 대상은 `{inst.id}`로 고정돼 있다.

## 지킬 것
{first_step}- 시작하면 `ch_editor_status`로 연결된 프로젝트가 {inst.name}인지 확인한다. 다르면 아무것도 바꾸지 말고 감독에게 보고한다.
- Unity 도구는 `{key}` 서버 것만 쓴다. 호출에 `unity_instance`를 넣지 않는다.
- 다른 프로젝트 일을 받으면 하지 말고, 그 프로젝트 담당(unity-…)에게 넘겨야 한다고 감독에게 돌려준다.
- 씬 저장(`manage_scene`의 `save`)은 요청받았을 때만 한다.

## 작업 순서: 스냅샷 → ref → 행동 → 확인
1. `ch_scene_snapshot`으로 씬을 보고 대상의 ref(`@s1a2b3c4:e5` 형태)를 고른다. 씬이 크면 `depth`를 낮추고 `root=<ref>`로 파고든다.
2. `ch_*` 도구에는 ref를, MCP for Unity 기본 도구에는 노드의 `path`나 `instance_id`를 넘긴다.
3. 바꾼 뒤에는 스냅샷을 다시 찍어 결과를 확인한다. `STALE_REF`가 나오면 새 스냅샷의 ref를 쓴다.
4. 오류의 `retry`가 `safe`면 그대로 다시, `after_fix`면 인자를 고쳐서, `check_first`면 상태부터 확인하고 다시 한다.
5. `ch_*` 도구가 목록에 없으면 먼저 `manage_tools(action="sync")`로 Unity의 도구 목록을 다시 받아온다. 그래도 없으면 `execute_custom_tool(tool_name="ch_scene_snapshot", parameters={{...}})`처럼 부른다.

## 다른 프로젝트와 오브젝트 주고받기
- 보낼 때: 스냅샷으로 ref 확인 → `ch_export_objects(refs=[...], name="...")` → 결과의 `manifest_path`를 그대로 감독에게 돌려준다.
- 받을 때: `ch_import_package(manifest=..., dry_run=true)`로 먼저 확인한다. `would_overwrite`, `same_guid_elsewhere`, `missing_packages`, `warnings` 중 하나라도 있으면 멈추고 감독에게 그대로 보고한다. 문제가 없으면 `dry_run` 없이 실행하고, 결과의 `placed` ref를 보고한다.
- Blender가 보낸 모델(`claude-hand/model@1` manifest, FBX)을 받을 때: `ch_import_model(manifest=...)`. 결과의 `placed` ref와 `warnings`를 보고한다.

## 보고
마지막 답에는 한 일, 바뀐 것(ref, 경로, manifest_path), 남은 문제를 짧게 적는다. 감독이 다른 세션에 그대로 넘길 값은 정확히 옮긴다.
"""


