def read_json_file(path: Path) -> dict:
    """{} for a missing file; refuses to touch a file that is not valid JSON."""
    if not path.exists():
        return {}
    try:
        data = json.loads(path.read_text(encoding="utf-8") or "{}")
    except ValueError as exc:
        raise SystemExit(f"{path} is not valid JSON ({exc}); fix or move it, then run again.")
    if not isinstance(data, dict):
        raise SystemExit(f"{path} does not hold a JSON object.")
    return data


def direct_app_servers(files: list[Path] | None = None) -> list[str]:
    """MCP servers in the user's Claude config that operate Unity or Blender directly: MCP for Unity, Unity AI
    Assistant's relay, MCP for Blender. The supervisor must not use them (it would skip its subagents and their
    guard); the subagents run their own pinned copies under other names, so denying these does not touch them."""
    keys: set[str] = set()
    for file in files if files is not None else candidate_config_files():
        try:
            data = json.loads(file.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        for servers in _server_maps(data):
            for key, entry in servers.items():
                if key == CHAT_SERVER_NAME or not isinstance(entry, dict):
                    continue
                if looks_like_unity_server(key, entry) or is_unity_ai_relay(entry) or looks_like_blender_server(key, entry):
                    keys.add(key)
    return sorted(keys)


def plan_chat_config(root: Path = REPO_ROOT, runner: str = "uv run -q --no-project",
                     direct_servers: list[str] | None = None) -> dict[Path, dict]:
    """Files chat-setup writes on this machine, as {path: new contents}; only files that change.
    .mcp.json registers the channel for this folder (the channels docs' way). settings.local.json
    pre-allows the reply tool, so answering a panel never stops for a permission prompt. Both stay
    out of git: they hold this machine's paths and this user's permission choices."""
    plan: dict[Path, dict] = {}
    mcp_path = root / ".mcp.json"
    mcp = read_json_file(mcp_path)
    parts = runner.split()
    entry = {
        "command": parts[0],
        "args": [*parts[1:], (root / "tools" / "chat_channel.py").as_posix()],
        # Passed on explicitly: Claude Code is not documented to hand its whole environment to MCP servers.
        "env": {"CLAUDE_HAND_SUPERVISOR": "${CLAUDE_HAND_SUPERVISOR:-0}"},
    }
    if mcp.get("mcpServers", {}).get(CHAT_SERVER_NAME) != entry:
        mcp.setdefault("mcpServers", {})[CHAT_SERVER_NAME] = entry
        plan[mcp_path] = mcp
    settings_path = root / ".claude" / "settings.local.json"
    settings = read_json_file(settings_path)
    changed = False
    allow = settings.setdefault("permissions", {}).setdefault("allow", [])
    for rule in (CHAT_REPLY_RULE, CHAT_CONTEXT_RULE):
        if rule not in allow:
            allow.append(rule)
            changed = True
    # Approves this folder's .mcp.json entry up front so the first start asks one question fewer.
    # Claude Code applies approvals from settings.local.json only once the folder is trusted.
    enabled = settings.setdefault("enabledMcpjsonServers", [])
    if CHAT_SERVER_NAME not in enabled:
        enabled.append(CHAT_SERVER_NAME)
        changed = True
    # The supervisor works through its subagents only: no direct Unity/Blender tools in this folder's sessions.
    deny = settings["permissions"].setdefault("deny", [])
    for key in direct_servers if direct_servers is not None else direct_app_servers():
        rule = f"mcp__{key}__*"
        if rule not in deny:
            deny.append(rule)
            changed = True
    if changed:
        plan[settings_path] = settings
    return plan


AGENT_ALLOW_RE = re.compile(r"^mcp__(unity|blender)_[a-z0-9_]+__\*$")


def plan_tool_allow(root: Path, server_keys: list[str], prune: bool = False) -> dict[Path, dict]:
    """sync --allow-tools: let the supervisor's subagents use their Unity/Blender tools without a
    prompt each time (rules live in this folder's settings.local.json, so only the supervisor gets them)."""
    path = root / ".claude" / "settings.local.json"
    settings = read_json_file(path)
    allow = settings.setdefault("permissions", {}).setdefault("allow", [])
    wanted = [f"mcp__{key}__*" for key in server_keys]
    new = [rule for rule in allow if not (prune and AGENT_ALLOW_RE.match(rule) and rule not in wanted)]
    new += [rule for rule in wanted if rule not in new]
    if new == allow:
        return {}
    settings["permissions"]["allow"] = new
    return {path: settings}


def permission_path(path: str) -> str:
    """An absolute path as permission rules spell it: //abs/path, and on Windows C:/x becomes //c/x."""
    path = path.replace("\\", "/")
    if re.match(r"^[A-Za-z]:/", path):
        return f"//{path[0].lower()}{path[2:]}"
    return f"/{path}" if path.startswith("/") else path


def plan_notes_allow(root: Path, notes_paths: list[str]) -> dict[Path, dict]:
    """Let the supervisor keep, and its subagents read, the windows' notes files without a prompt: those files
    sit in the user's project folders, outside this one, where Read and Edit otherwise ask every time."""
    path = root / ".claude" / "settings.local.json"
    settings = read_json_file(path)
    allow = settings.setdefault("permissions", {}).setdefault("allow", [])
    new = [f"{tool}({permission_path(p)})" for p in notes_paths if p for tool in ("Read", "Edit")]
    new = [rule for rule in dict.fromkeys(new) if rule not in allow]
    if not new:
        return {}
    allow += new
    return {path: settings}


def write_json_files(plan: dict[Path, dict]) -> None:
    for path, data in plan.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")


def prewarm_chat_channel(root: Path = REPO_ROOT, runner: str = "uv run -q --no-project", run=subprocess.run) -> dict:
    """Start the channel once the way Claude Code will, with --check: uv fetches Python now (not inside
    Claude Code's 30-second MCP startup window) and we learn whether the port and home folder work."""
    parts = runner.split()
    exe = shutil.which(parts[0]) or parts[0]
    try:
        proc = run([exe, *parts[1:], str(root / "tools" / "chat_channel.py"), "--check"],
                   capture_output=True, text=True, errors="replace", timeout=600)
    except (OSError, subprocess.TimeoutExpired) as exc:
        return {"ok": False, "error": f"could not run {parts[0]}: {exc}"}
    for line in reversed((proc.stdout or "").strip().splitlines()):
        try:
            return json.loads(line)
        except ValueError:
            continue
    return {"ok": False, "error": (proc.stderr or proc.stdout or "no output").strip()[-500:]}


def parse_claude_version(text: str | None) -> tuple[int, ...] | None:
    match = re.search(r"(\d+)\.(\d+)\.(\d+)", text or "")
    return tuple(int(x) for x in match.groups()) if match else None


